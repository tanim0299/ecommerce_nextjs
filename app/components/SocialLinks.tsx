'use client';

import React from 'react';
import { useApp, SocialLink } from '../context';

interface SocialLinksProps {
  className?: string;
  itemClassName?: string;
  variant?: 'dark' | 'light' | 'card';
  iconSizeClass?: string;
}

export default function SocialLinks({
  className = '',
  itemClassName = '',
  variant = 'dark',
  iconSizeClass = 'w-4.5 h-4.5',
}: SocialLinksProps) {
  const { systemConfig, resolveImageUrl } = useApp();
  const links = systemConfig?.social_links || [];
  const [failedImages, setFailedImages] = React.useState<Record<string, boolean>>({});

  if (!links || links.length === 0) {
    return null;
  }

  const getVariantStyles = () => {
    switch (variant) {
      case 'light':
        return 'bg-slate-100 hover:bg-brand-orange text-slate-700 hover:text-white border border-slate-200/80 shadow-xs hover:border-brand-orange';
      case 'card':
        return 'bg-white hover:bg-brand-orange text-slate-800 hover:text-white border border-slate-200 shadow-xs hover:border-brand-orange hover:shadow-md';
      case 'dark':
      default:
        return 'bg-slate-900 border border-slate-800 hover:border-brand-orange hover:text-brand-orange text-slate-400 shadow-sm hover:shadow-brand-orange/20';
    }
  };

  const renderIcon = (social: SocialLink, sIdx: number) => {
    const titleText = social.title || social.platform || 'Social Link';
    const iconVal = (social.icon || '').trim();
    const fallbackKey = `${titleText}-${sIdx}`;

    // Check if icon is an image URL/path (uploaded file or external URL)
    const isImageIcon = Boolean(
      iconVal &&
      !failedImages[fallbackKey] &&
      (iconVal.startsWith('http://') ||
       iconVal.startsWith('https://') ||
       iconVal.startsWith('/') ||
       iconVal.includes('system/') ||
       iconVal.includes('storage/') ||
       iconVal.match(/\.(png|jpg|jpeg|webp|svg|gif)($|\?)/i))
    );

    if (isImageIcon) {
      const resolvedImg = resolveImageUrl(iconVal);
      return (
        <img
          src={resolvedImg}
          alt={titleText}
          className={`${iconSizeClass} object-contain transition-all group-hover:scale-110`}
          onError={() => {
            setFailedImages((prev) => ({ ...prev, [fallbackKey]: true }));
          }}
        />
      );
    }

    if (iconVal.startsWith('<svg')) {
      return (
        <span
          className={`${iconSizeClass} flex items-center justify-center fill-current`}
          dangerouslySetInnerHTML={{ __html: iconVal }}
        />
      );
    }

    const key = (iconVal || social.name || social.platform || '').toLowerCase().trim();
    switch (key) {
      case 'facebook':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M24 12.073c0-6.627-5.373-12-12-12s-12 5.373-12 12c0 5.99 4.388 10.954 10.125 11.854v-8.385H7.078v-3.47h3.047V9.43c0-3.007 1.792-4.669 4.533-4.669 1.312 0 2.686.235 2.686.235v2.953H15.83c-1.491 0-1.956.925-1.956 1.874v2.25h3.328l-.532 3.47h-2.796v8.385C19.612 23.027 24 18.062 24 12.073z"/>
          </svg>
        );
      case 'instagram':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M12 2.163c3.204 0 3.584.012 4.85.07 3.252.148 4.771 1.691 4.919 4.919.058 1.265.069 1.645.069 4.849 0 3.205-.012 3.584-.069 4.849-.149 3.225-1.664 4.771-4.919 4.919-1.266.058-1.644.07-4.85.07-3.204 0-3.584-.012-4.849-.07-3.26-.149-4.771-1.699-4.919-4.92-.058-1.265-.07-1.644-.07-4.849 0-3.204.013-3.583.07-4.849.149-3.227 1.664-4.771 4.919-4.919 1.266-.057 1.645-.069 4.849-.069zm0-2.163c-3.259 0-3.667.014-4.947.072-4.358.2-6.78 2.618-6.98 6.98-.059 1.281-.073 1.689-.073 4.948 0 3.259.014 3.668.072 4.948.2 4.358 2.618 6.78 6.98 6.98 1.281.058 1.689.072 4.948.072 3.259 0 3.668-.014 4.948-.072 4.354-.2 6.782-2.618 6.979-6.98.059-1.28.073-1.689.073-4.948 0-3.259-.014-3.667-.072-4.947-.196-4.354-2.617-6.78-6.979-6.98-1.281-.059-1.69-.073-4.949-.073zm0 5.838c-3.403 0-6.162 2.759-6.162 6.162s2.759 6.163 6.162 6.163 6.162-2.759 6.162-6.163c0-3.403-2.759-6.162-6.162-6.162zm0 10.162c-2.209 0-4-1.79-4-4 0-2.209 1.791-4 4-4s4 1.791 4 4c0 2.21-1.791 4-4 4zm6.406-11.845c-.796 0-1.441.645-1.441 1.44s.645 1.44 1.441 1.44c.795 0 1.439-.645 1.439-1.44s-.644-1.44-1.439-1.44z"/>
          </svg>
        );
      case 'youtube':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M23.498 6.186a3.016 3.016 0 0 0-2.122-2.136C19.505 3.545 12 3.545 12 3.545s-7.505 0-9.377.505A3.017 3.017 0 0 0 .502 6.186C0 8.07 0 12 0 12s0 3.93.502 5.814a3.016 3.016 0 0 0 2.122 2.136c1.871.505 9.376.505 9.376.505s7.505 0 9.377-.505a3.015 3.015 0 0 0 2.122-2.136C24 15.93 24 12 24 12s0-3.93-.502-5.814zM9.545 15.568V8.432L15.818 12l-6.273 3.568z"/>
          </svg>
        );
      case 'tiktok':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M12.525.02c1.31-.02 2.61-.01 3.91-.02.08 1.53.63 3.09 1.75 4.17 1.12 1.11 2.7 1.62 4.24 1.79v4.03c-1.44-.05-2.89-.35-4.2-.97-.57-.26-1.1-.59-1.62-.93-.01 2.92.01 5.84-.02 8.75-.08 1.4-.54 2.79-1.35 3.94-1.31 1.92-3.58 3.17-5.91 3.21-1.43.08-2.86-.31-4.08-1.03-2.02-1.19-3.44-3.37-3.65-5.71-.02-.5-.03-1-.01-1.49.18-1.9 1.12-3.72 2.58-4.96 1.66-1.44 3.98-2.13 6.15-1.72.02 1.48-.04 2.96-.04 4.44-.99-.32-2.15-.23-3.02.37-.63.41-1.11 1.04-1.36 1.75-.21.51-.24 1.07-.14 1.61.24 1.64 1.82 2.89 3.5 2.77 1.81-.03 3.32-1.48 3.42-3.29.09-2.31.06-4.63.06-6.95.01-4.52-.02-9.04.03-13.56z"/>
          </svg>
        );
      case 'twitter':
      case 'x':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M18.244 2.25h3.308l-7.227 8.26 8.502 11.24H16.17l-5.214-6.817L4.99 21.75H1.68l7.73-8.835L1.254 2.25H8.08l4.713 6.231zm-1.161 17.52h1.833L7.084 4.126H5.117z"/>
          </svg>
        );
      case 'whatsapp':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M.057 24l1.687-6.163c-1.041-1.804-1.588-3.849-1.587-5.946.003-6.556 5.338-11.891 11.893-11.891 3.181.001 6.167 1.24 8.413 3.488 2.245 2.248 3.481 5.236 3.48 8.414-.003 6.557-5.338 11.892-11.893 11.892-1.99-.001-3.951-.5-5.688-1.448l-6.305 1.654zm6.597-3.807c1.676.995 3.276 1.591 5.392 1.592 5.448 0 9.886-4.434 9.889-9.885.002-5.462-4.415-9.89-9.881-9.892-5.452 0-9.887 4.434-9.889 9.884-.001 2.225.651 3.891 1.746 5.634l-.999 3.648 3.742-.981z"/>
          </svg>
        );
      case 'linkedin':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M19 3a2 2 0 0 1 2 2v14a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h14m-.5 15.5v-5.3a3.26 3.26 0 0 0-3.26-3.26c-.85 0-1.84.52-2.28 1.3v-1.11h-2.79v8.37h2.79v-4.93c0-.77.62-1.4 1.39-1.4a1.4 1.4 0 0 1 1.4 1.4v4.93h2.75M6.88 8.56a1.68 1.68 0 0 0 1.68-1.68c0-.93-.75-1.69-1.68-1.69a1.69 1.69 0 0 0-1.69 1.69c0 .93.76 1.68 1.69 1.68m1.39 9.94v-8.37H5.5v8.37h2.77z"/>
          </svg>
        );
      case 'telegram':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M12 2C6.48 2 2 6.48 2 12s4.48 10 10 10 10-4.48 10-10S17.52 2 12 2zm4.64 6.8c-.15 1.58-.8 5.42-1.13 7.19-.14.75-.42 1-.68 1.03-.58.05-1.02-.38-1.58-.75-.88-.58-1.38-.94-2.23-1.5-.99-.65-.35-1.01.22-1.59.15-.15 2.71-2.48 2.76-2.69a.2.2 0 0 0-.05-.18c-.06-.05-.14-.03-.21-.02-.09.02-1.49.95-4.22 2.79-.4.27-.76.41-1.08.4-.36-.01-1.04-.2-1.55-.37-.63-.2-1.12-.31-1.08-.66.02-.18.27-.36.75-.55 2.92-1.27 4.86-2.11 5.83-2.51 2.78-1.16 3.35-1.36 3.73-1.36.08 0 .27.02.39.12.1.08.13.19.14.27-.01.06.01.24 0 .38z"/>
          </svg>
        );
      case 'pinterest':
        return (
          <svg className={`${iconSizeClass} fill-current`} viewBox="0 0 24 24">
            <path d="M12 0C5.373 0 0 5.372 0 12c0 5.084 3.163 9.426 7.627 11.174-.105-.949-.2-2.405.042-3.441.218-.937 1.407-5.965 1.407-5.965s-.359-.719-.359-1.782c0-1.668.967-2.914 2.171-2.914 1.023 0 1.518.769 1.518 1.69 0 1.029-.655 2.568-.994 3.995-.283 1.194.599 2.169 1.777 2.169 2.133 0 3.772-2.249 3.772-5.495 0-2.873-2.064-4.882-5.012-4.882-3.414 0-5.418 2.561-5.418 5.207 0 1.031.397 2.138.893 2.738.098.119.112.224.083.345-.09.375-.291 1.199-.332 1.357-.053.211-.174.256-.402.155-1.499-.696-2.435-2.883-2.435-4.643 0-3.779 2.746-7.252 7.92-7.252 4.158 0 7.392 2.967 7.392 6.923 0 4.135-2.607 7.462-6.233 7.462-1.214 0-2.354-.629-2.758-1.379l-.749 2.848c-.269 1.045-1.004 2.352-1.498 3.146 1.123.345 2.306.535 3.55.535 6.627 0 12-5.373 12-12 0-6.628-5.373-12-12-12z"/>
          </svg>
        );
      default:
        return (
          <span className="text-[11px] font-black uppercase leading-none">
            {titleText[0] || 'S'}
          </span>
        );
    }
  };

  return (
    <div className={`flex items-center gap-2.5 flex-wrap ${className}`}>
      {links.map((social, sIdx) => {
        const targetUrl = social.url || social.link || '#';
        const titleText = social.title || social.platform || 'Social Link';

        return (
          <a
            key={social.title || social.platform || sIdx}
            href={targetUrl}
            target="_blank"
            rel="noopener noreferrer"
            className={`w-8 h-8 rounded-lg flex items-center justify-center transition-all duration-300 hover:scale-110 active:scale-95 cursor-pointer group overflow-hidden ${getVariantStyles()} ${itemClassName}`}
            title={titleText}
            aria-label={titleText}
          >
            {renderIcon(social, sIdx)}
          </a>
        );
      })}
    </div>
  );
}
